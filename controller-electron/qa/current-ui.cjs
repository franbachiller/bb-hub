const {app,BrowserWindow,ipcMain}=require('electron');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {ControllerCore}=require('../electron/controller-core.cjs');
const {normalizeHotkey}=require('../electron/hotkey.cjs');
const root=path.resolve(__dirname,'..');
app.disableHardwareAcceleration();
app.whenReady().then(async()=>{
  const core=new ControllerCore({ringBoard:false,settingsPath:'D:/bb-hub-build-temp-1003/ui-unused-settings.json'});
  const win=new BrowserWindow({show:false,width:1260,height:820,webPreferences:{preload:path.join(root,'electron/preload.cjs'),sandbox:true,contextIsolation:true,nodeIntegration:false,backgroundThrottling:false}});
  let updates={status:'idle',version:'0.1.1',message:''};
  const snapshot=()=>({...core.snapshot(),updates});
  const publish=()=>win.webContents.send('controller:snapshot',snapshot());
  ipcMain.handle('controller:getSnapshot',snapshot);
  ipcMain.handle('controller:setTimingHotkey',(_e,value)=>{core.timingHotkey=normalizeHotkey(value);publish();return core.timingHotkey;});
  const errors=[];
  win.webContents.on('console-message',event=>{if(event.level==='error')errors.push(event.message);});
  await win.loadFile(path.join(root,'dist-ui/index.html'));
  win.showInactive();
  await new Promise(r=>setTimeout(r,300));
  assert.equal(await win.webContents.executeJavaScript(`document.querySelector('[aria-label="Activar Board"]').disabled`),true);
  assert.equal(await win.webContents.executeJavaScript(`document.body.innerText.includes('licencia Pro')`),false);
  await win.webContents.executeJavaScript(`document.querySelectorAll('.rail-link')[2].click()`);
  await new Promise(r=>setTimeout(r,150));
  const basic=await win.webContents.executeJavaScript(`({tiles:document.querySelectorAll('.preview-tile').length,frame:document.querySelectorAll('iframe').length,
    locked:document.querySelector('.board-tools').disabled,arm:document.querySelector('.btn-outline-accent').disabled,text:document.body.innerText,
    overflow:document.documentElement.scrollWidth>innerWidth})`);
  assert.equal(basic.tiles,117);assert.equal(basic.frame,0);assert.equal(basic.locked,true);assert.equal(basic.arm,true);assert.equal(basic.overflow,false);
  for(const label of ['Planner','Tile2','Ofensivo','Alta potencia','Vista previa'])assert.ok(basic.text.includes(label));
  await win.webContents.executeJavaScript(`new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))`);
  fs.writeFileSync(path.join(root,'../tmp/bb-board-pro-preview-1003.png'),(await win.webContents.capturePage()).toPNG());
  await win.webContents.executeJavaScript(`document.querySelectorAll('.rail-link')[1].click()`);
  await new Promise(r=>setTimeout(r,150));
  assert.equal(await win.webContents.executeJavaScript(`document.querySelector('[aria-label="Modo automático"]').disabled`),true);
  await win.webContents.executeJavaScript(`{const input=document.querySelector('[aria-label="Atajo de Timing"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'Ctrl+F4');input.dispatchEvent(new Event('input',{bubbles:true}));}`);
  await win.webContents.executeJavaScript(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='Guardar atajo').click()`);
  await new Promise(r=>setTimeout(r,150));
  assert.equal(core.timingHotkey,'Control+F4');
  assert.equal(await win.webContents.executeJavaScript(`document.querySelector('[aria-label="Atajo de Timing"]').value`),'Control+F4');
  await win.webContents.executeJavaScript(`new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))`);
  fs.writeFileSync(path.join(root,'../tmp/bb-timing-hotkey-1003.png'),(await win.webContents.capturePage()).toPNG());
  updates={status:'available',version:'0.1.1',nextVersion:'0.1.2',message:'Versión 0.1.2 disponible.'};publish();
  await new Promise(r=>setTimeout(r,100));
  assert.ok(await win.webContents.executeJavaScript(`document.body.innerText.includes('Descargar e instalar')`));
  assert.deepEqual(errors,[]);
  win.setSize(980,680);
  await win.webContents.executeJavaScript(`document.querySelectorAll('.rail-link')[2].click()`);
  await win.webContents.executeJavaScript(`new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))`);
  assert.equal(await win.webContents.executeJavaScript(`document.documentElement.scrollWidth>innerWidth || document.querySelector('.board-tools').scrollWidth>document.querySelector('.board-tools').clientWidth`),false);
  fs.writeFileSync(path.join(root,'../tmp/bb-board-preview-980-1003.png'),(await win.webContents.capturePage()).toPNG());
  const persistencePath=path.join(fs.mkdtempSync('D:/bb-hub-build-temp-1003/hotkey-settings-'),'settings.json');
  core.settingsPath=persistencePath;
  core.persistSettings();
  const restored=new ControllerCore({ringBoard:false,settingsPath:persistencePath});
  assert.equal(restored.timingHotkey,'Control+F4');
  restored.stop();
  console.log('PASS: current dark Hub, Basic preview visible with controls disabled and no live iframe, Timing shortcut saved, update notice visible.');
  core.stop();app.quit();
}).catch(error=>{console.error(error);app.exit(1);});
